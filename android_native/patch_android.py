#!/usr/bin/env python3
"""Adds the built-in GeckoView (Firefox engine) Google sign-in to the
Flutter-generated android/ runner. Run from the project root after
`flutter create . --platforms=android` (the CI workflow does this).
Idempotent: safe to run on every build."""
import os
import re
import shutil

GECKO_VERSION = os.environ.get('GECKOVIEW_VERSION', '152.0.20260713164047')
# GeckoView 152 ships kotlin-stdlib 2.3.x + androidx.core 1.18 (fits the AGP
# 8.9 / compileSdk 36 of Flutter 3.35; GeckoView 154+ needs AGP 9.1).
KOTLIN_VERSION = os.environ.get('KOTLIN_VERSION', '2.3.21')

here = os.path.dirname(os.path.abspath(__file__))
root = os.getcwd()
android = os.path.join(root, 'android')
app = os.path.join(android, 'app')
assert os.path.isdir(app), 'run from the project root after flutter create'


def read(p):
    with open(p, encoding='utf-8') as f:
        return f.read()


def write(p, s):
    with open(p, 'w', encoding='utf-8') as f:
        f.write(s)


# 1) Kotlin sources next to the generated MainActivity.kt
main_kt = None
for d, _, files in os.walk(os.path.join(app, 'src', 'main')):
    if 'MainActivity.kt' in files:
        main_kt = os.path.join(d, 'MainActivity.kt')
        break
kt_dir = os.path.dirname(main_kt) if main_kt else os.path.join(
    app, 'src', 'main', 'kotlin', 'com', 'aistudio', 'ai_image_studio')
os.makedirs(kt_dir, exist_ok=True)
pkg = 'com.aistudio.ai_image_studio'
if main_kt:
    m = re.search(r'^package\s+([\w.]+)', read(main_kt), re.M)
    if m:
        pkg = m.group(1)
for name in ('MainActivity.kt', 'GeckoBridge.kt', 'GeckoSignInActivity.kt',
             'GeckoBrowserActivity.kt', 'GenerationService.kt'):
    s = read(os.path.join(here, 'kotlin', name))
    s = re.sub(r'^package\s+[\w.]+', 'package ' + pkg, s, count=1, flags=re.M)
    write(os.path.join(kt_dir, name), s)

# 2) built-in WebExtension
dst = os.path.join(app, 'src', 'main', 'assets', 'ais_cookies')
if os.path.isdir(dst):
    shutil.rmtree(dst)
shutil.copytree(os.path.join(here, 'assets', 'ais_cookies'), dst)
# content.js = touch flag + the SAME overlay the Windows app injects
# (lib/browser/overlay_script.dart) + the bridge to background.js.
dart = read(os.path.join(root, 'lib', 'browser', 'overlay_script.dart'))
start = dart.index("r'''") + 4
overlay = dart[start:dart.index("''';", start)]
bridge = read(os.path.join(dst, 'content_bridge.js'))
os.remove(os.path.join(dst, 'content_bridge.js'))
write(os.path.join(dst, 'content.js'),
      '// Generated by android_native/patch_android.py - do not edit.\n'
      'window.__aisTouchUI = true;\n' + overlay + '\n' + bridge)

# 3) manifest: sign-in activity
mp = os.path.join(app, 'src', 'main', 'AndroidManifest.xml')
s = read(mp)
if 'GeckoBrowserActivity' not in s:
    s = s.replace('</application>', '''    <activity
            android:name=".GeckoBrowserActivity"
            android:exported="false"
            android:theme="@android:style/Theme.Material.NoActionBar"
            android:configChanges="orientation|keyboardHidden|keyboard|screenSize|smallestScreenSize|screenLayout|density|uiMode"
            android:windowSoftInputMode="adjustResize" />
    </application>''', 1)
if 'GeckoSignInActivity' not in s:
    s = s.replace('</application>', '''    <activity
            android:name=".GeckoSignInActivity"
            android:exported="false"
            android:theme="@android:style/Theme.Material.Light.NoActionBar"
            android:configChanges="orientation|keyboardHidden|keyboard|screenSize|smallestScreenSize|screenLayout|density|uiMode"
            android:windowSoftInputMode="adjustResize" />
    </application>''', 1)
if 'GenerationService' not in s:
    s = s.replace('</application>', '''    <service
            android:name=".GenerationService"
            android:exported="false"
            android:foregroundServiceType="dataSync" />
    </application>''', 1)
# Background generation: foreground service + wake / Wi-Fi locks.
for perm in ('WAKE_LOCK', 'FOREGROUND_SERVICE', 'FOREGROUND_SERVICE_DATA_SYNC',
             'POST_NOTIFICATIONS', 'REQUEST_IGNORE_BATTERY_OPTIMIZATIONS',
             'ACCESS_WIFI_STATE', 'ACCESS_NETWORK_STATE'):
    if 'android.permission.' + perm + '"' not in s:
        s = re.sub(r'(<manifest[^>]*>)',
                   r'\1\n    <uses-permission android:name="android.permission.%s"/>' % perm,
                   s, count=1)
if 'android.permission.INTERNET' not in s:
    s = re.sub(r'(<manifest[^>]*>)',
               r'\1\n    <uses-permission android:name="android.permission.INTERNET"/>',
               s, count=1)
write(mp, s)

# 4) Mozilla maven repository
for p in (os.path.join(android, 'build.gradle.kts'),
          os.path.join(android, 'settings.gradle.kts')):
    s = read(p)
    if 'maven.mozilla.org' in s:
        continue
    if p.endswith('build.gradle.kts'):
        s = s.replace('        mavenCentral()\n',
                      '        mavenCentral()\n'
                      '        maven { url = uri("https://maven.mozilla.org/maven2/") }\n', 1)
    else:
        s = re.sub(r'id\("org\.jetbrains\.kotlin\.android"\) version "[^"]+"',
                   'id("org.jetbrains.kotlin.android") version "%s"' % KOTLIN_VERSION, s)
    write(p, s)

# 5) app module: dependency, arm64 only (GeckoView native libs), minSdk 26
bg = os.path.join(app, 'build.gradle.kts')
s = read(bg)
# Kotlin >= 2.3 rejects the old kotlinOptions { jvmTarget = ... } DSL.
s = re.sub(r'\n\s*kotlinOptions\s*\{[^}]*\}\n', '\n', s)
s = s.replace('JavaVersion.VERSION_11', 'JavaVersion.VERSION_17')
if 'compilerOptions' not in s:
    s += '''
kotlin {
    compilerOptions {
        jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
    }
}
'''
if 'org.mozilla.geckoview' not in s:
    # Compress native libs in the APK (GeckoView's libxul is ~150 MB raw).
    s = s.replace('    defaultConfig {',
                  '    packaging {\n'
                  '        jniLibs { useLegacyPackaging = true }\n'
                  '    }\n\n'
                  '    defaultConfig {', 1)
    s = s.replace('        minSdk = flutter.minSdkVersion',
                  '        minSdk = maxOf(flutter.minSdkVersion, 26)\n'
                  '        ndk { abiFilters += listOf("arm64-v8a") }', 1)
    s += '''
dependencies {
    // Built-in Firefox engine for the Google (Gemini) sign-in screen.
    implementation("org.mozilla.geckoview:geckoview-arm64-v8a:%s")
}
''' % GECKO_VERSION
write(bg, s)
print('GeckoView sign-in added (geckoview %s, kotlin %s, package %s)'
      % (GECKO_VERSION, KOTLIN_VERSION, pkg))
